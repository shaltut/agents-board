// #4765: one source of rules for every agent. Claude Code reads CLAUDE.md; the others read AGENTS.md.
//   node cli/agent-context.ts repo [--check]    this repo's AGENTS.md, made from its CLAUDE.md
//   node cli/agent-context.ts user [--check] [--agents codex,agy,opencode]
//     each installed agent's user-level rules file gets a copy of ~/.claude/CLAUDE.md, in a marked block, beside what the
//     file already says. Per machine, under the home folder, never in git. It sends that file to each agent's model
//     provider, so only the owner runs it: a squad seat may only --check.
import { existsSync, lstatSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { ADAPTERS, AGENT_KINDS, isAgentKind, type AgentKind } from './agents/index.ts';

const BEGIN = '<!-- cb:user-rules begin';
const END = '<!-- cb:user-rules end -->';
const BEGIN_LINE = `${BEGIN}: a copy of the Claude Code user rules. Edit ~/.claude/CLAUDE.md, then run: node cli/agent-context.ts user -->`;
const USAGE = 'usage: node cli/agent-context.ts repo [--check] | node cli/agent-context.ts user [--check] [--agents codex,agy,opencode]';

const unix = (s: string) => s.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
const textOf = (file: string) => (existsSync(file) ? readFileSync(file, 'utf8') : null);
// one file under two names: a symbolic link or a hard link
const sameFile = (a: string, b: string) => {
  const x = statSync(a, { bigint: true }), y = statSync(b, { bigint: true });
  return x.dev === y.dev && x.ino === y.ino;
};

export const agentsMdFrom = (claudeMd: string): string =>
  `<!-- Made from CLAUDE.md. Do not edit this file: edit CLAUDE.md, then run: node cli/agent-context.ts repo -->\n\n${unix(claudeMd)}`;

export type RulesState = 'written' | 'same' | 'differs' | 'skipped' | 'linked';
export type RulesResult = { agent: AgentKind; file: string; state: RulesState };

/** The file's text with the block holding `rules`. A file with no block gets one at the end. */
function withBlock(now: string | null, rules: string, file: string): string {
  const crlf = !!now?.includes('\r\n');
  const text = unix(now ?? '');
  const block = `${BEGIN_LINE}\n${rules.replace(/\n*$/, '\n')}${END}`;
  const begins = text.split(BEGIN).length - 1, ends = text.split(END).length - 1;
  const from = text.indexOf(BEGIN), to = text.indexOf(END);
  let out: string;
  if (!begins && !ends) out = `${text && `${text.replace(/\n*$/, '')}\n\n`}${block}\n`;
  else if (begins === 1 && ends === 1 && from < to) out = text.slice(0, from) + block + text.slice(to + END.length);
  else throw new Error(`${file} has a half or doubled cb:user-rules block: nothing was changed. Delete its marker lines and the old copy, then run again`);
  return crlf ? out.replace(/\n/g, '\r\n') : out;
}

export function syncUserRules(o: { home: string; env: NodeJS.ProcessEnv; agents?: string[]; check?: boolean }): RulesResult[] {
  // either name makes a pane a seat
  if (!o.check && (o.env.CB_ROLE?.trim() || o.env.CB_AGENT?.trim())) throw new Error('a squad seat does not write the owner\'s user files: the owner runs this in their own terminal (--check is fine in a seat)');
  const source = join(o.env.CLAUDE_CONFIG_DIR || join(o.home, '.claude'), 'CLAUDE.md');
  const raw = textOf(source);
  if (raw === null) throw new Error(`no ${source}: there is nothing to copy`);
  const rules = unix(raw);
  if (!rules.trim()) throw new Error(`${source} is empty: nothing was changed`);
  if (rules.includes(BEGIN) || rules.includes(END)) throw new Error(`${source} holds a cb:user-rules marker line: remove it, or the block cannot be found again`);

  const asked = [...new Set(o.agents ?? AGENT_KINDS.filter((k) => ADAPTERS[k].userRulesFile(o.home, o.env) !== null))];
  // every file is read and judged before the first write
  const plan = asked.map((agent) => {
    if (!isAgentKind(agent)) throw new Error(`unknown agent "${agent}"`);
    const file = ADAPTERS[agent].userRulesFile(o.home, o.env);
    if (file === null) throw new Error(`${agent} reads the source file itself: leave it out of --agents`);
    // no config folder: the agent is not on this machine
    if (!existsSync(dirname(file))) return { agent, file, state: 'skipped' as const };
    // a link to nothing reads as no file, and the write would follow it and make its target, wherever that is
    if (!existsSync(file) && lstatSync(file, { throwIfNoEntry: false })?.isSymbolicLink()) {
      throw new Error(`${file} is a link to a file that is not there: nothing was changed. Remove the link or make its target, then run again`);
    }
    // writing through a link to the source would put a copy of the source inside itself
    if (existsSync(file) && sameFile(file, source)) return { agent, file, state: 'linked' as const };
    const now = textOf(file), next = withBlock(now, rules, file);
    return { agent, file, state: next === now ? 'same' as const : 'differs' as const, next };
  });
  return plan.map(({ agent, file, state, next }: { agent: AgentKind; file: string; state: RulesState; next?: string }) => {
    if (o.check || state !== 'differs') return { agent, file, state };
    writeFileSync(file, next!);
    return { agent, file, state: 'written' };
  });
}

function main(argv: string[]) {
  const { values, positionals } = parseArgs({ args: argv, allowPositionals: true, options: { check: { type: 'boolean' }, agents: { type: 'string' } } });
  const [what, ...rest] = positionals;
  if (rest.length || (what !== 'repo' && what !== 'user') || (what === 'repo' && values.agents !== undefined)) throw new Error(USAGE);
  if (what === 'user') {
    const agents = values.agents?.split(',').map((s) => s.trim()).filter(Boolean);
    if (agents && !agents.length) throw new Error(USAGE); // an empty list would do nothing and say nothing
    const done = syncUserRules({ home: homedir(), env: process.env, check: values.check, agents });
    for (const r of done) console.log(`${r.agent}: ${r.state}${r.state === 'skipped' ? ' (no config folder on this machine)' : ''} ${r.file}`);
    if (values.check && done.some((r) => r.state === 'differs')) process.exitCode = 1;
    return;
  }
  const root = fileURLToPath(new URL('..', import.meta.url));
  const file = join(root, 'AGENTS.md'), want = agentsMdFrom(readFileSync(join(root, 'CLAUDE.md'), 'utf8'));
  if (unix(textOf(file) ?? '') === want) console.log('AGENTS.md: same');
  else if (values.check) throw new Error('AGENTS.md is not what CLAUDE.md makes. Run: node cli/agent-context.ts repo');
  else { writeFileSync(file, want); console.log('AGENTS.md: written'); }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(process.argv.slice(2)); } catch (e: any) {
    console.error(e.code?.startsWith?.('ERR_PARSE_ARGS') ? `${e.message}\n${USAGE}` : e.message);
    process.exitCode = 1;
  }
}
